# physics agent: generates crates/velocity_physics/src/c_config_mem.rs (byte images of CGlobalConfig /
# CLocalConfig as the game sees them, plus expression lookup by field offset)
import re
root = r"D:\projects\project poland rewrite\crates\velocity_physics\src"
src = open(root + r"\c_config.rs", encoding="utf-8").read()
out = ["//! Byte images of the config structs (`CGlobalConfig` 0x870 bytes, `CLocalConfig` 744 bytes) as the game",
       "//! code addresses them. Expression members hold their own field offset, so a pointer read from an",
       "//! expression slot names the expression. Generated by tools/phys_gen_cfgmem.py.",
       "#![allow(clippy::all)]", "",
       "use crate::c_config::{CGlobalConfig, CLocalConfig};",
       "use crate::fastcar::mem::Mem;",
       "use crate::vehicle::vs_config_file_read::Expression;", ""]
for name, size, a, b in (("CGlobalConfig", 0x880, "pub struct CGlobalConfig", "pub enum LoadResult"),
                         ("CLocalConfig", 744, "pub struct CLocalConfig", "/// variables of `sensitivity_into_turn`")):
    body = src[src.index(a):src.index(b)]
    sets, exprs = [], []
    for m in re.finditer(r"pub (\w+): (.+?), // \+0x([0-9A-F]+)", body):
        n, ty, o = m.group(1), m.group(2).strip(), int(m.group(3), 16)
        if ty == "f32":
            sets.append("m.set_f(%d, self.%s);" % (o, n))
        elif ty == "i32":
            sets.append("m.set_i(%d, self.%s);" % (o, n))
        elif ty == "Expression":
            sets.append("m.set_i(%d, %d);" % (o, o))
            exprs.append("%d => &self.%s," % (o, n))
        elif re.match(r"\[f32; \d+\]$", ty):
            for k in range(int(re.findall(r"\d+", ty)[1])):
                sets.append("m.set_f(%d, self.%s[%d]);" % (o + 4 * k, n, k))
        elif re.match(r"\[i32; \d+\]$", ty):
            for k in range(int(re.findall(r"\d+", ty)[1])):
                sets.append("m.set_i(%d, self.%s[%d]);" % (o + 4 * k, n, k))
        elif re.match(r"\[Expression; \d+\]$", ty):
            for k in range(int(re.findall(r"\d+", ty)[0])):
                sets.append("m.set_i(%d, %d);" % (o + 4 * k, o + 4 * k))
                exprs.append("%d => &self.%s[%d]," % (o + 4 * k, n, k))
        elif re.match(r"\[\[Expression; 4\]; 6\]$", ty):
            for k in range(24):
                sets.append("m.set_i(%d, %d);" % (o + 4 * k, o + 4 * k))
                exprs.append("%d => &self.%s[%d][%d]," % (o + 4 * k, n, k // 4, k % 4))
        elif re.match(r"\[\[i32; 4\]; 6\]$", ty):
            for k in range(24):
                sets.append("m.set_i(%d, self.%s[%d][%d]);" % (o + 4 * k, n, k // 4, k % 4))
        elif ty.startswith("Vec<"):
            sets.append("// %s: heap pointer, not addressed through the image" % n)
        else:
            raise SystemExit("unhandled %s %s" % (n, ty))
    out.append("impl %s {" % name)
    out.append("    /// the struct as the game's memory image")
    out.append("    pub fn to_mem(&self) -> Mem {")
    out.append("        let mut m = Mem::new(%d);" % size)
    out += ["        " + s for s in sets]
    out.append("        m")
    out.append("    }")
    out.append("")
    out.append("    /// expression member at byte offset `off`")
    out.append("    pub fn expr_at(&self, off: usize) -> Option<&Expression> {")
    out.append("        Some(match off {")
    out += ["            " + s for s in exprs]
    out.append("            _ => return None,")
    out.append("        })")
    out.append("    }")
    out.append("}")
    out.append("")
open(root + r"\c_config_mem.rs", "w", encoding="utf-8").write("\n".join(out))
print("ok")
